const REGIONS_ES: Record<string, string> = { unova: 'Teselia' };

const MACHINE_PREFIXES_ES: Record<string, string> = { TM: 'MT', HM: 'MO', TR: 'DT' };

let current: Lang = 'en';
let typeLabels: Record<string, string> = {};

export const setLang = (lang: Lang): void => { current = lang; };
export const getLang = (): Lang => current;

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return MESSAGES[current][key].replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}

export const plural = (count: number, one: Key, many: Key): string => t(count === 1 ? one : many, { n: count });

const capitalize = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);
const titleWords = (slug: string): string => slug.split('-').map(capitalize).join(' ');

// Type names come from PokeAPI (meta.typeLabels); without them the slug is
// shown and CSS capitalizes it.
export const setTypeLabels = (labels: Record<string, string> | undefined): void => { typeLabels = labels || {}; };
export const typeLabel = (type: string): string => typeLabels[type] || type;
export const typeName = (type: string): string => typeLabels[type] || capitalize(type);

export const statLabel = (stat: string): string => t(`stat.${stat}` as Key);

export const learnMethodLabel = (method: string): string =>
  (current === 'es' && LEARN_METHODS_ES[method]) || titleWords(method);

export const growthRateLabel = (rate: string): string => GROWTH_RATES[current][rate] || titleWords(rate);

export const regionName = (region: string): string => (current === 'es' && REGIONS_ES[region]) || capitalize(region);

export function machineLabel(label: string): string {
  const prefix = label.slice(0, 2);
  return current === 'es' && MACHINE_PREFIXES_ES[prefix] ? MACHINE_PREFIXES_ES[prefix] + label.slice(2) : label;
}

// "Red & Blue" in English; "Rojo y Azul", "X e Y" in Spanish ("e" before an /i/ sound).
export function joinNames(names: string[], lang: Lang = current): string {
  if (lang === 'en' || names.length < 2) return names.join(' & ');
  const last = names[names.length - 1];
  const and = /^(i|hi(?!e)|y$)/i.test(last) ? ' e ' : ' y ';
  return names.slice(0, -1).join(', ') + and + last;
}

export const localeOf = (lang: Lang = current): string => (lang === 'es' ? 'es-ES' : 'en-US');

export const decimal = (n: number): string =>
  n.toLocaleString(localeOf(), { minimumFractionDigits: 1, maximumFractionDigits: 1 });

export const integer = (n: number): string => n.toLocaleString(localeOf());

export function percent(n: number): string {
  const text = n.toLocaleString(localeOf(), { maximumFractionDigits: 1 });
  return current === 'es' ? `${text} %` : `${text}%`;
}

export const compareText = (a: string, b: string): number => a.localeCompare(b, localeOf(), { numeric: true });

// English pages live at the site root and every other language in its own
// folder (es/), which also holds its data, so relative "data/..." URLs work
// from any page. Shared assets (css, js, icons) stay at the root.
export const langDir = (lang: Lang = current): string => (lang === 'en' ? '' : `${lang}/`);
export const rootPath = (lang: Lang = current): string => (lang === 'en' ? '' : '../');
